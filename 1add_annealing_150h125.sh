#!/usr/bin/env bash

# ============================================================
# INCREMENTAL EMMI ANNEALING-PHASE PROCESSING
#
# Purpose:
#   Add ONLY the phase annealing_T=150_h=125 after the original
#   automatic pipeline has already been run.
#
# CRITICAL GLOBAL-ID POLICY:
#   - existing global hotspot IDs are NEVER recomputed;
#   - the existing shared sensor-level catalog is the immutable seed;
#   - a detected hotspot within MATCH_RADIUS of an existing catalog
#     entry keeps that global ID;
#   - a genuinely new hotspot receives max(existing global ID) + 1,
#     then the counter increases monotonically;
#   - T-constant is processed before v-constant, so a hotspot first
#     discovered in T can immediately be reused by v in the same phase;
#   - historical rows already written in merged CSV files are never
#     recalculated or overwritten: only new rows are appended.
#
# Usage:
#   ./2add_annealing_150h125.sh A1
#   ./2add_annealing_150h125.sh B1
#
# The script must be located in the main "emmi" directory.
# ============================================================

set -Eeuo pipefail
