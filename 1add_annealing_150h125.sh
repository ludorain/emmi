            "Inspect/remove stale partial outputs before re-running."
        )

    new_detection_paths[constant] = detection_output
    new_complete_paths[constant] = complete_output


alignment_rows = pd.read_csv(alignment_rows_path)
check_columns(
    alignment_rows,
    alignment_rows_path,
    [
        "phase", "constant", "run_prefix", "run_number", "angle",
        "clipy", "clipx", "shifty", "shiftx", "is_primary_reference",
    ],
)

if len(alignment_rows) != 2:
    raise RuntimeError(
        f"Expected exactly 2 new alignment rows (T and v), "
        f"found {len(alignment_rows)} in {alignment_rows_path}."
    )

if set(alignment_rows["phase"].astype(str)) != {phase}:
    raise RuntimeError(
        f"Temporary alignment rows do not all belong to phase {phase}."
    )

if set(alignment_rows["constant"].astype(str)) != set(CONSTANTS):
    raise RuntimeError(
        "Temporary alignment table must contain exactly T and v."
    )


# ============================================================
# TRANSACTIONAL APPEND
# ============================================================
#
# Existing CSV rows are never re-generated.
# We back up every historical file that will receive appended rows.
# If any write fails, every file is restored from backup and every newly
# created merged file for this phase is removed.

timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
backup_dir = (
    data_dir / "incremental_backups"
    / f"{sensor}_{phase}_{timestamp}"
)
backup_dir.mkdir(parents=True, exist_ok=False)

append_targets = [
    shared_catalog_path,
    shared_mapping_path,
    real_alignment_path,
]

for constant in CONSTANTS:
    append_targets.extend(paths_by_constant[constant].values())

# Deduplicate while preserving order.
unique_targets = []
seen_targets = set()
for path in append_targets:
    resolved = str(path.resolve())
    if resolved not in seen_targets:
        unique_targets.append(path)
        seen_targets.add(resolved)

backup_map = {}

for index, target in enumerate(unique_targets):
    if not target.is_file():
        raise FileNotFoundError(
            f"Historical file disappeared before transaction: {target}"
        )

    backup_name = (
        f"{index:02d}__{target.parent.name}__{target.name}"
    )
    backup_path = backup_dir / backup_name
    shutil.copy2(target, backup_path)
    backup_map[target] = backup_path

manifest = backup_dir / "MANIFEST.txt"
with manifest.open("w", encoding="utf-8") as handle:
    handle.write(
        f"Incremental backup before adding {phase} for sensor {sensor}\n"
    )
    for target, backup in backup_map.items():
        handle.write(f"{target} <- {backup.name}\n")

created_merged_files = []

try:
    # 1) Brand-new catalog IDs only.
    if not new_catalog_df.empty:
        append_dataframe_preserving_existing_bytes(
            shared_catalog_path, new_catalog_df
        )
        for constant in CONSTANTS:
            append_dataframe_preserving_existing_bytes(
                paths_by_constant[constant]["catalog"],
                new_catalog_df,
            )

    # 2) Real detections/mapping for the new phase.
    append_dataframe_preserving_existing_bytes(
        shared_mapping_path, mapping_new
    )

    for constant in CONSTANTS:
        append_dataframe_preserving_existing_bytes(
            paths_by_constant[constant]["mapping"],
            mapping_new[mapping_new["constant"] == constant],
        )

    # 3) Current-phase presence, phase-change summary and geometry plan.
    for constant in CONSTANTS:
        append_dataframe_preserving_existing_bytes(
            paths_by_constant[constant]["presence"],
            presence_current_by_constant[constant],
        )
        append_dataframe_preserving_existing_bytes(
            paths_by_constant[constant]["phase_changes"],
            phase_changes_current_by_constant[constant],
        )
        append_dataframe_preserving_existing_bytes(
            paths_by_constant[constant]["geometry_plan"],
            geometry_current_by_constant[constant],
        )

    # 4) Current-phase forced measurements are appended to the canonical
    #    master; all historical master rows remain untouched.
    for constant in CONSTANTS:
        append_dataframe_preserving_existing_bytes(
            paths_by_constant[constant]["master"],
            complete_current_by_constant[constant],
        )

    # 5) Write the two phase-specific merged products.
    for d in matched_datasets:
        constant = d["constant"]

        atomic_write_new_csv(
            new_detection_paths[constant],
            d["df_global"],
        )
        created_merged_files.append(new_detection_paths[constant])

        atomic_write_new_csv(
            new_complete_paths[constant],
            complete_current_by_constant[constant],
        )
        created_merged_files.append(new_complete_paths[constant])

    # 6) Alignment metadata is appended LAST, after every scientific output
    #    has been successfully written.
    append_dataframe_preserving_existing_bytes(
        real_alignment_path, alignment_rows
    )

except BaseException:
    print(
        "\nERROR DURING FINAL APPEND: restoring every historical file "
        "from the incremental backup...",
        file=sys.stderr,
    )

    for target, backup in backup_map.items():
        shutil.copy2(backup, target)

    for path in created_merged_files:
        try:
            if path.exists():
                path.unlink()
        except OSError:
            pass

    raise


# ============================================================
# FINAL REPORT
# ============================================================

print("")
print("============================================================")
print("INCREMENTAL PHASE ADDED SUCCESSFULLY")
print(f"Sensor: {sensor}")
print(f"Phase:  {phase}")
print(f"Original maximum global ID: {initial_max_id}")
print(f"New IDs created: {len(new_global_ids)}")

if new_global_ids:
    print(
        "New global-ID range: "
        f"{min(new_global_ids)} .. {max(new_global_ids)}"
    )
else:
    print("No new global IDs were needed.")

for d in matched_datasets:
    constant = d["constant"]
    n_detected = len(d["present_spots"])
    n_new_local = int(
        (mapping_new["constant"].eq(constant)
         & mapping_new["match_type"].eq("new")).sum()
    )

    print(
        f"{constant}-constant: detected={n_detected}, "
        f"new IDs first created in this scan={n_new_local}"
    )
    print(f"  global_ID:       {new_detection_paths[constant]}")
    print(f"  global_complete: {new_complete_paths[constant]}")
    print(f"  master appended: {paths_by_constant[constant]['master']}")

print(f"Shared catalog appended: {shared_catalog_path}")
print(f"Shared mapping appended: {shared_mapping_path}")
print(f"Alignment appended:      {real_alignment_path}")
print(f"Safety backup retained:  {backup_dir}")
print("============================================================")
PY_INCREMENTAL
}


