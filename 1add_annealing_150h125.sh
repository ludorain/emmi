    header = list(pd.read_csv(path, nrows=0).columns)
    aligned = frame.copy()

    for col in header:
        if col not in aligned.columns:
            aligned[col] = np.nan

    aligned = aligned[header]
    aligned.to_csv(path, mode="a", header=False, index=False)


