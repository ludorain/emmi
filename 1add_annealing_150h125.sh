# clipy/clipx are defined here as the symmetric number of pixels removed
# PER SIDE by rotate-image.py, inferred from the actual input/output shapes.
# If rotate-image.py preserves the input dimensions, both values are zero.
measure_rotation_clip() {
    local input_image="$1"
    local rotated_image="$2"

    "$PYTHON" - "$input_image" "$rotated_image" <<'PY'
import sys
import tifffile

before = tifffile.imread(sys.argv[1])
after = tifffile.imread(sys.argv[2])

if before.ndim < 2 or after.ndim < 2:
    raise SystemExit("Rotation clipping check requires at least 2D images.")

ny0, nx0 = before.shape[-2:]
ny1, nx1 = after.shape[-2:]

dy = ny0 - ny1
dx = nx0 - nx1

if dy < 0 or dx < 0:
    # The rotation enlarged the canvas instead of clipping it.
    # For the requested metadata, no pixels were removed.
    clipy = 0.0
    clipx = 0.0
else:
    clipy = dy / 2.0
    clipx = dx / 2.0

print(f"{clipy:g} {clipx:g}")
PY
}

