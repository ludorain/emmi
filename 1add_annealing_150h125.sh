def write_complete_coordinate_file(d, phase_plan: pd.DataFrame) -> Path:
    coord_output = d["run_dir"] / "4coordinates" / (
        f"{d['run_prefix']}_{phase}_run={d['run_number']}"
        "_incremental_global_complete_coordinates.txt"
    )

    ordered = phase_plan.sort_values("spot")

    with coord_output.open("w", encoding="utf-8") as handle:
        for row in ordered.itertuples(index=False):
            handle.write(
                f"{row.x:.6f}, {row.y:.6f}, "
                f"{row.integration_area:.6f}, "
                f"{row.integration_radius:.6f}\n"
            )

    return coord_output


def map_root_results_to_plan(result_df: pd.DataFrame,
                             phase_plan: pd.DataFrame,
                             root_file: Path) -> pd.DataFrame:
    needed = ["x", "y", "luminosity", "error"]
    check_columns(result_df, root_file, needed)

    result = result_df.copy()
    for col in needed:
        result[col] = pd.to_numeric(result[col], errors="raise")

    result["result_index"] = np.arange(len(result), dtype=int)

    plan = phase_plan.copy().reset_index(drop=True)
    plan["plan_index"] = np.arange(len(plan), dtype=int)

    if len(result) != len(plan):
        raise RuntimeError(
            f"ROOT returned {len(result)} rows for {root_file}, "
            f"but {len(plan)} global coordinates were supplied."
        )

    mapping, _, _ = greedy_one_to_one(
        source_rows=result,
        target_rows=plan,
        source_id="result_index",
        target_id="plan_index",
        sx="x",
        sy="y",
        tx="x",
        ty="y",
        radius=coord_match_radius,
    )

    if len(mapping) != len(result):
        raise RuntimeError(
            f"Could not map every ROOT luminosity result back to the "
            f"current global coordinate plan for {root_file}."
        )

    plan_lookup = plan.set_index("plan_index")
    records = []

    for result_row in result.itertuples(index=False):
        p = plan_lookup.loc[mapping[result_row.result_index]]

        records.append({
            "spot": int(p["spot"]),
            "x": float(p["x"]),
            "y": float(p["y"]),
            "luminosity": float(result_row.luminosity),
            "error": float(result_row.error),
            "integration_area": float(p["integration_area"]),
            "integration_radius": float(p["integration_radius"]),
            "phase": p["phase"],
            "run_number": p["run_number"],
            "detection": p["detection"],
            "status": p["status"],
            "geometry_source_phase": p["geometry_source_phase"],
            "geometry_source_constant": p["geometry_source_constant"],
            "geometry_source_run": p["geometry_source_run"],
            "geometry_mode": p["geometry_mode"],
            "integration_radius_source_phase":
                p["integration_radius_source_phase"],
            "integration_radius_source_constant":
                p["integration_radius_source_constant"],
            "integration_radius_source_run":
                p["integration_radius_source_run"],
            "match_distance": p["match_distance"],
            "cross_constant_only": bool(p["cross_constant_only"]),
        })

    return pd.DataFrame(records)


def run_forced_measurements(d, phase_plan: pd.DataFrame):
    constant = d["constant"]
    coord_file = write_complete_coordinate_file(d, phase_plan)
    frames = []

    print(
        f"Forced measurement {phase} / {constant}: "
        f"{len(phase_plan)} global hotspots, "
        f"{len(d['root_files'])} TH2F files"
    )

    for root_file in d["root_files"]:
        t_value = extract_parameter_from_name(root_file.name, "T")
        v_value = extract_parameter_from_name(root_file.name, "v")

        result_csv = spot_lum_dir / "luminosity_results.csv"
        if result_csv.exists():
            result_csv.unlink()

        macro_call = f'{spot_lum_macro}("{root_file}","{coord_file}")'
        completed = subprocess.run(
            ["root", "-l", "-q", macro_call],
            cwd=spot_lum_dir,
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )

        if completed.returncode != 0:
            print(completed.stdout, file=sys.stderr)
            raise RuntimeError(
                f"ROOT luminosity macro failed for {root_file} "
                f"with exit code {completed.returncode}."
            )

        if not result_csv.is_file():
            print(completed.stdout, file=sys.stderr)
            raise RuntimeError(
                f"ROOT did not create luminosity_results.csv for {root_file}."
            )

        raw = pd.read_csv(result_csv)
        result_csv.unlink()

        measured = map_root_results_to_plan(raw, phase_plan, root_file)
        measured["T"] = t_value
        measured["v"] = v_value

        if constant == "T":
            measured["v_fin"] = (
                v_value - float(vbd_text) if vbd_text else np.nan
            )

        frames.append(measured)

    complete = pd.concat(frames, ignore_index=True)
    varying = "v" if constant == "T" else "T"

    return complete.sort_values(
        ["spot", varying], kind="stable"
    ).reset_index(drop=True)


def reorder_complete_columns(df: pd.DataFrame):
    preferred = ["spot", "x", "y", "luminosity", "error", "T", "v"]

    if "v_fin" in df.columns:
