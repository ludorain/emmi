def sort_detection_rows(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df
    tmp = df.copy()
    tmp["__phase_sort"] = tmp["phase"].astype(str).map(phase_sort_key)
    tmp["__constant_sort"] = tmp["constant"].map(CONSTANT_ORDER).fillna(99)
    return tmp.sort_values(
        ["__phase_sort", "__constant_sort"], kind="stable"
