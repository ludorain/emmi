}

# ------------------------------------------------------------
# SHIFT HELPERS
# ------------------------------------------------------------
# ALLINEAMENTO/TRASLAZIONE (SHIFT):
# Confronta l'immagine "light" del set corrente con l'immagine "light" di 
# riferimento primario (quella della fase before_annealing) per trovare di
# quanti pixel l'immagine è spostata. Applica poi questa traslazione x/y
# a tutte le immagini per sovrapporle perfettamente al riferimento.

assert_same_image_shape() {
    local reference="$1"
    local moving="$2"

    "$PYTHON" - "$reference" "$moving" <<'PY'
import sys
import tifffile

ref = tifffile.imread(sys.argv[1])
mov = tifffile.imread(sys.argv[2])

if ref.shape != mov.shape:
    raise SystemExit(
        "Reference and moving light images have different shapes after rotation:\n"
        f"  reference: {ref.shape}\n"
        f"  moving:    {mov.shape}\n"
        "measure-shift.py should only be run on geometrically compatible images."
    )
PY
}

