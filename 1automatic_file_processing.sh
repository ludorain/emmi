# ------------------------------------------------------------
# PHASE STEP 1 - IMAGE CLEANUP
# ------------------------------------------------------------
# FASE 1: PULIZIA DELLE IMMAGINI
# Questa fase applica gli script Python per rimuovere i bias di colonna e filtrare
# gli hot/cold pixel. Questo viene fatto SOLO sui file di dati, mentre le immagini
# di errore (*_data=diffe.tif*) vengono copiate intatte, per mantenere integro
# il calcolo dell'errore.
cleanup_images() {
    local run_dir="$1"

    local originals_dir="$run_dir/1originals"
    local processed_dir="$run_dir/2processed"

    [[ -d "$originals_dir" ]] \
        || die "Missing input directory: $originals_dir"

    mkdir -p "$processed_dir"

    log "1/5 - Image cleanup: $(basename "$run_dir")"

    local n_files=0
    local input_file filename stem output_file

    while IFS= read -r -d '' input_file; do
        filename="$(basename "$input_file")"
        stem="$(strip_tif_extension "$filename")"
        output_file="$processed_dir/${stem}_processed.tif"

        # --- MODIFICA AGGIUNTA ---
        # Se il file è un'immagine di errore (data=diffe),
        # copiamo semplicemente il file senza pulirlo.
        if [[ "$filename" == *"data=diffe"* ]]; then
            cp "$input_file" "$output_file"
        else
            # Altrimenti applichiamo la pulizia
            "$PYTHON" "$PROCESS_IMAGE" \
                --input "$input_file" \
                --process remove_column_bias remove_hot_pixels remove_cold_pixels \
                --output "$output_file"
        fi

        ((n_files += 1))
    done < <(
        find "$originals_dir" \
            -maxdepth 1 \
            -type f \
            \( -iname '*.tif' -o -iname '*.tiff' \) \
            -print0
    )

    (( n_files > 0 )) \
        || die "No TIF files found in $originals_dir"
}

# ------------------------------------------------------------
# ROTATION HELPERS
# ------------------------------------------------------------
# ROTAZIONE DELLE IMMAGINI:
# Analizza l'immagine di fondo ("light") per calcolare l'angolo di inclinazione 
# rispetto all'orizzontale. Una volta trovato l'angolo, tutte le immagini (dati ed errori)
# del run corrente vengono ruotate per farle allineare geometricamente.

get_unique_light_image() {
    local directory="$1"

    local matches=()
    local f

    while IFS= read -r -d '' f; do
        matches+=("$f")
    done < <(
        find "$directory" \
            -maxdepth 1 \
            -type f \
            \( -iname '*.tif' -o -iname '*.tiff' \) \
            -name '*data=light*' \
            -print0
    )

    (( ${#matches[@]} > 0 )) \
        || die "No data=light TIF image found in $directory"

    (( ${#matches[@]} == 1 )) \
        || die "More than one data=light image found in $directory"

    printf '%s\n' "${matches[0]}"
}

measure_rotation_angle() {
    local light_image="$1"
    local output angle

    output="$(
        "$PYTHON" "$MEASURE_ROTATION" --input "$light_image"
    )"

    printf '%s\n' "$output" >&2

    angle="$(
        printf '%s\n' "$output" |
        "$PYTHON" -c '
import re
import sys

text = sys.stdin.read()
m = re.search(
    r"rotation angle:\s*([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)",
    text
)

if m is None:
    raise SystemExit("Cannot parse rotation angle from measure-rotation.py output.")

print(m.group(1))
'
    )"

    printf '%s\n' "$angle"
}

# clipy/clipx are defined here as the symmetric number of pixels removed
# PER SIDE by rotate-image.py, inferred from the actual input/output shapes.
# If rotate-image.py preserves the input dimensions, both values are zero.
measure_rotation_clip() {
    local input_image="$1"
    local rotated_image="$2"

    "$PYTHON" - "$input_image" "$rotated_image" <<'PY'
import sys
import tifffile

before = tifffile.imread(sys.argv[1])
after = tifffile.imread(sys.argv[2])

if before.ndim < 2 or after.ndim < 2:
    raise SystemExit("Rotation clipping check requires at least 2D images.")

ny0, nx0 = before.shape[-2:]
ny1, nx1 = after.shape[-2:]

dy = ny0 - ny1
dx = nx0 - nx1

if dy < 0 or dx < 0:
    # The rotation enlarged the canvas instead of clipping it.
    # For the requested metadata, no pixels were removed.
    clipy = 0.0
    clipx = 0.0
else:
    clipy = dy / 2.0
    clipx = dx / 2.0

print(f"{clipy:g} {clipx:g}")
PY
}

