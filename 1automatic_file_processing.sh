        phase,
    )
    if m:
        return (1, float(m.group(1)), float(m.group(2)), phase)

    return (2, math.inf, math.inf, phase)


def extract_parameter_from_name(filename: str, parameter: str) -> float:
    m = re.search(
        rf"(?:^|_){re.escape(parameter)}="
        rf"([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)",
        filename,
    )
    if m is None:
