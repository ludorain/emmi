def mean_coordinates_per_local_spot(df: pd.DataFrame) -> pd.DataFrame:
    tmp = df.copy()
    tmp["x"] = pd.to_numeric(tmp["x"], errors="raise")
    tmp["y"] = pd.to_numeric(tmp["y"], errors="raise")
    return (
        tmp.groupby("spot", as_index=False, sort=True)
        .agg(x_mean=("x", "mean"), y_mean=("y", "mean"))
    )


def greedy_one_to_one(source_rows, target_rows, source_id, target_id,
                      sx, sy, tx, ty, radius):
    """Return one-to-one nearest-neighbour mapping within radius."""
    pairs = []
    candidate_counts = {}

    for _, src in source_rows.iterrows():
        sid = src[source_id]
        n_candidates = 0

        for _, tgt in target_rows.iterrows():
            tid = tgt[target_id]
            distance = math.hypot(
                float(src[sx]) - float(tgt[tx]),
                float(src[sy]) - float(tgt[ty]),
            )
            if distance <= radius:
                pairs.append((distance, sid, tid))
                n_candidates += 1

        candidate_counts[sid] = n_candidates

    pairs.sort(key=lambda item: item[0])

    assigned_source = set()
    assigned_target = set()
    mapping = {}
    distances = {}

    for distance, sid, tid in pairs:
        if sid in assigned_source or tid in assigned_target:
            continue
        mapping[sid] = tid
        distances[sid] = distance
        assigned_source.add(sid)
        assigned_target.add(tid)

    return mapping, distances, candidate_counts


def read_reference_coordinates(path: Path) -> pd.DataFrame:
    rows = []
    with path.open("r", encoding="utf-8") as handle:
        for line_number, raw in enumerate(handle, start=1):
            line = raw.strip()
            if not line:
                continue

            fields = [part.strip() for part in line.split(",")]
            if len(fields) < 4:
                raise ValueError(
                    f"Invalid coordinate line {line_number} in {path}: {raw.rstrip()}"
                )

            try:
                x, y, area, radius = map(float, fields[:4])
            except ValueError as exc:
                raise ValueError(
                    f"Non-numeric coordinate line {line_number} in {path}: "
                    f"{raw.rstrip()}"
                ) from exc

            rows.append({
                "coord_index": len(rows),
                "x_coord": x,
                "y_coord": y,
                "integration_area": area,
                "integration_radius": radius,
            })

    if not rows:
        raise RuntimeError(f"Coordinate file is empty: {path}")

    return pd.DataFrame(rows)


def attach_local_geometry(local_spots: pd.DataFrame, coordinates: pd.DataFrame,
                          phase: str, constant: str):
    mapping, distances, candidate_counts = greedy_one_to_one(
        source_rows=local_spots,
        target_rows=coordinates,
        source_id="spot",
        target_id="coord_index",
        sx="x_mean",
        sy="y_mean",
        tx="x_coord",
        ty="y_coord",
        radius=coord_match_radius,
    )

    missing = [spot for spot in local_spots["spot"] if spot not in mapping]
    if missing:
        raise RuntimeError(
            f"Could not associate local spots with the 4coordinates file in "
            f"phase={phase}, constant={constant}. Missing local spot IDs: {missing}. "
            f"Increase COORD_MATCH_RADIUS only if the coordinate systems are known "
            f"to differ slightly."
        )

    coord_lookup = coordinates.set_index("coord_index")
    geometry = {}

    for local_spot, coord_index in mapping.items():
        row = coord_lookup.loc[coord_index]
        geometry[local_spot] = {
            "x": float(row["x_coord"]),
            "y": float(row["y_coord"]),
            "integration_area": float(row["integration_area"]),
            "integration_radius": float(row["integration_radius"]),
            "coordinate_match_distance": float(distances[local_spot]),
        }

        if candidate_counts.get(local_spot, 0) > 1:
            print(
                "WARNING: multiple coordinate-file candidates within tolerance: "
                f"phase={phase}, constant={constant}, local_spot={local_spot}",
                file=sys.stderr,
            )

    return geometry


