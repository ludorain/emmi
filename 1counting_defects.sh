check_requirements() {
    command -v "$PYTHON" >/dev/null 2>&1 \
        || die "Python executable not found: $PYTHON"

    command -v root >/dev/null 2>&1 \
        || die "ROOT executable 'root' not found in PATH."

    local required_files=(
        "$PROCESS_IMAGE"
        "$TIF2TH2"
