SPOT_LUM_DIR="$BASE_DIR/spot_luminosity"
SPOT_LUM_MACRO="spot_luminosity_sum_irradiated.C"

PYTHON="${PYTHON:-python3}"

# Spatial tolerance used in PHASE 3 to identify the same hotspot
