# ------------------------------------------------------------
# FILENAME / DIRECTORY HELPERS
# ------------------------------------------------------------

extract_run_number() {
    local run_dir="$1"
    local name
    name="$(basename "$run_dir")"

    if [[ "$name" =~ _run=(.+)$ ]]; then
        printf '%s\n' "${BASH_REMATCH[1]}"
    else
        die "Cannot extract run number from directory: $run_dir"
    fi
}

extract_run_prefix() {
    local run_dir="$1"
    local name
    name="$(basename "$run_dir")"

    if [[ "$name" =~ ^(.+)_run=.+$ ]]; then
        printf '%s\n' "${BASH_REMATCH[1]}"
    else
        die "Cannot extract run prefix from directory: $run_dir"
    fi
}

find_selected_run_dir() {
    local phase_dir="$1"
    local pattern="${SENSOR}_${CONSTANT}=*_run=*"

    local matches=()
    while IFS= read -r -d '' d; do
        matches+=("$d")
    done < <(
        find "$phase_dir" \
            -mindepth 1 -maxdepth 1 \
            -type d \
            -name "$pattern" \
            -print0
    )

    if (( ${#matches[@]} == 0 )); then
        return 1
    fi

    if (( ${#matches[@]} > 1 )); then
        printf 'ERROR: more than one directory matches %s in %s:\n' \
            "$pattern" "$phase_dir" >&2
        printf '  %s\n' "${matches[@]}" >&2
        die "The selected sensor/constant must identify exactly one run per phase."
    fi

    printf '%s\n' "${matches[0]}"
}

strip_tif_extension() {
    local name="$1"
    name="${name%.tif}"
    name="${name%.TIF}"
    name="${name%.tiff}"
    name="${name%.TIFF}"
    printf '%s\n' "$name"
}

# Extract T or v from an EMMI filename.
extract_parameter() {
    local filename="$1"
    local parameter="$2"

    "$PYTHON" - "$filename" "$parameter" <<'PY'
import os
import re
import sys

name = os.path.basename(sys.argv[1])
parameter = sys.argv[2]

m = re.search(
    rf'(?:^|_){re.escape(parameter)}=([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)',
    name
)

if m is None:
    raise SystemExit(
        f"Cannot extract parameter {parameter!r} from filename: {name}"
    )

print(m.group(1))
PY
}

