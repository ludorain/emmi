# ------------------------------------------------------------
# PHASE STEP 3 - REFERENCE COORDINATES
# ------------------------------------------------------------

select_second_highest_reference() {
    local rotated_dir="$1"

    local varying_parameter
    if [[ "$CONSTANT" == "T" ]]; then
        varying_parameter="v"
    else
        varying_parameter="T"
    fi

    "$PYTHON" - "$rotated_dir" "$varying_parameter" <<'PY'
from pathlib import Path
import re
import sys

directory = Path(sys.argv[1])
parameter = sys.argv[2]

# Only the differential emission images are candidates.
files = sorted(directory.glob("*data=diff*_processed_rotated.tif"))

# Exclude data=diffe explicitly, because "data=diffe" also contains "data=diff".
files = [f for f in files if "data=diffe" not in f.name]

pattern = re.compile(
    rf"(?:^|_){re.escape(parameter)}="
    rf"([-+]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][-+]?\d+)?)"
)

entries = []
for f in files:
    m = pattern.search(f.name)
    if m:
        entries.append((float(m.group(1)), f))

if not entries:
    raise SystemExit(
        f"No data=diff images with parameter {parameter}=... found in {directory}"
    )

distinct_values = sorted({value for value, _ in entries}, reverse=True)

if len(distinct_values) < 2:
    raise SystemExit(
        f"Cannot select the second-highest {parameter}: "
        f"only {len(distinct_values)} distinct value(s) found in {directory}."
    )

target = distinct_values[1]
matches = [f for value, f in entries if value == target]

if len(matches) != 1:
    raise SystemExit(
        f"Expected exactly one reference image at second-highest "
        f"{parameter}={target}, found {len(matches)}."
    )

print(matches[0])
PY
}

generate_reference_coordinates() {
    local run_dir="$1"
    local phase="$2"
    local run_number="$3"
    local run_prefix="$4"

    local rotated_dir="$run_dir/3rotated"
    local coordinates_dir="$run_dir/4coordinates"

    mkdir -p "$coordinates_dir"

    log "3/5 - Reference coordinates: $phase / run=$run_number" >&2

    local ref_image
    ref_image="$(select_second_highest_reference "$rotated_dir")"

    local reference_coords
    reference_coords="$coordinates_dir/${run_prefix}_${phase}_run=${run_number}_reference_coordinates.txt"

    # Redirect the diagnostic stdout of the source-finding program to stderr:
    # this function itself prints ONLY the coordinate-file path on stdout,
    # because its caller captures that value with command substitution.
    "$PYTHON" "$FIND_DEFECTS" \
        --input "$ref_image" \
        --coordinates_root "$reference_coords" >&2

    [[ -s "$reference_coords" ]] \
        || die "Reference coordinate file was not created or is empty: $reference_coords"

    printf '%s\n' "$reference_coords"
}

# ------------------------------------------------------------
# PHASE STEP 4 - TIF -> TH2F
# ------------------------------------------------------------

convert_to_th2f() {
    local run_dir="$1"

    local rotated_dir="$run_dir/3rotated"
    local root_dir="$run_dir/5th2f"

    mkdir -p "$root_dir"

    log "4/5 - TIF to TH2F conversion: $(basename "$run_dir")"

    local input_file error_file filename stem output_file
    local n_converted=0

    while IFS= read -r -d '' input_file; do

        # Skip the uncertainty image itself.
        [[ "$input_file" == *"data=diffe"* ]] && continue

        error_file="${input_file/data=diff/data=diffe}"

        [[ -f "$error_file" ]] || die \
            "Missing matching data=diffe image for:\n  $input_file\nExpected:\n  $error_file"

        filename="$(basename "$input_file")"
        stem="$(strip_tif_extension "$filename")"
        output_file="$root_dir/${stem}_th2f.root"

        "$PYTHON" "$TIF2TH2" \
            --input "$input_file" \
            --error "$error_file" \
            --output "$output_file"

        ((n_converted += 1))

    done < <(
        find "$rotated_dir" \
            -maxdepth 1 \
            -type f \
            -name '*data=diff*_processed_rotated.tif' \
            -print0
    )

    (( n_converted > 0 )) \
        || die "No differential images converted in $rotated_dir"
}

# ------------------------------------------------------------
# PHASE STEP 5 - LUMINOSITY
# ------------------------------------------------------------

calculate_luminosity() {
    local run_dir="$1"
    local phase="$2"
    local run_number="$3"
    local run_prefix="$4"
    local reference_coords="$5"

    local root_dir="$run_dir/5th2f"
    local lum_dir="$run_dir/6luminosity"

    mkdir -p "$lum_dir"

    # Remove only intermediate CSV files generated by this pipeline,
    # so that stale files from an older execution are not merged.
    rm -f "$lum_dir"/luminosity_*_processed_rotated.csv

    log "5/5 - Luminosity calculation: $phase / run=$run_number"

    local root_file filename stem val_T val_v out_csv

    while IFS= read -r -d '' root_file; do
        filename="$(basename "$root_file")"
        stem="${filename%_th2f.root}"

        val_T="$(extract_parameter "$filename" "T")"
        val_v="$(extract_parameter "$filename" "v")"

        (
            cd "$SPOT_LUM_DIR"

            rm -f luminosity_results.csv

            root -l -q \
                "${SPOT_LUM_MACRO}(\"${root_file}\",\"${reference_coords}\")"

            [[ -f luminosity_results.csv ]] \
                || die "ROOT macro did not create luminosity_results.csv for $root_file"

            out_csv="$lum_dir/luminosity_${stem}.csv"

            awk -v t="$val_T" -v v="$val_v" '
                BEGIN {
                    FS=","
                    OFS=","
                }
                {
                    gsub(/[[:space:]]+$/, "", $0)

                    if ($0 != "") {
                        if (NR == 1)
                            print $0, "T", "v"
                        else
                            print $0, t, v
                    }
                }
            ' luminosity_results.csv > "$out_csv"

            rm -f luminosity_results.csv
        )

    done < <(
        find "$root_dir" \
            -maxdepth 1 \
            -type f \
            -name '*data=diff*_processed_rotated_th2f.root' \
            -print0
    )

    merge_luminosity_csvs \
        "$lum_dir" \
        "$phase" \
        "$run_number" \
        "$run_prefix"
}

merge_luminosity_csvs() {
    local lum_dir="$1"
    local phase="$2"
    local run_number="$3"
    local run_prefix="$4"

    local vbd
    vbd="$(get_vbd)"

    local output_name="${run_prefix}_${phase}_run=${run_number}.csv"
    local output_path="$lum_dir/$output_name"

    log "Merging luminosity CSVs -> $output_name"

    SENSOR_ENV="$SENSOR" \
    CONSTANT_ENV="$CONSTANT" \
    VBD_ENV="$vbd" \
    LUM_DIR_ENV="$lum_dir" \
    OUTPUT_PATH_ENV="$output_path" \
    "$PYTHON" <<'PY'
import glob
import os
import sys
import pandas as pd

sensor = os.environ["SENSOR_ENV"]
constant = os.environ["CONSTANT_ENV"]
vbd_text = os.environ.get("VBD_ENV", "")
lum_dir = os.environ["LUM_DIR_ENV"]
output_path = os.environ["OUTPUT_PATH_ENV"]

files = sorted(
    glob.glob(os.path.join(lum_dir, "luminosity_*_processed_rotated.csv"))
)

if not files:
    raise SystemExit(f"No luminosity intermediate CSV files found in {lum_dir}")

frames = []
for path in files:
    df = pd.read_csv(path)
    frames.append(df)

full_df = pd.concat(frames, ignore_index=True)

required = {"x", "y", "T", "v"}
missing = required.difference(full_df.columns)
if missing:
    raise SystemExit(
        "Missing required columns in luminosity CSV files: "
        + ", ".join(sorted(missing))
    )

# The ROOT macro is called with one common coordinate file for all
# operating conditions in this run, so identical x,y identify the same spot.
full_df["spot"] = full_df.groupby(["x", "y"], sort=True).ngroup()

columns = ["spot"] + [c for c in full_df.columns if c != "spot"]
full_df = full_df[columns]

full_df["T"] = pd.to_numeric(full_df["T"], errors="raise")
full_df["v"] = pd.to_numeric(full_df["v"], errors="raise")

if constant == "T":
    # T fixed -> v changes.
    # Keep absolute v and, when VBD is configured, add v_fin.
    if vbd_text.strip():
        vbd = float(vbd_text)
        full_df["v_fin"] = full_df["v"] - vbd
    else:
        # Do not invent a breakdown voltage.
        full_df["v_fin"] = float("nan")
        print(
            f"WARNING: VBD for {sensor} is not configured. "
            "Column v_fin is written as NaN; absolute v is preserved.",
            file=sys.stderr,
        )

    full_df = full_df.sort_values(
        by=["spot", "v"],
        kind="stable",
    )

else:
    # v fixed -> T changes.
    full_df = full_df.sort_values(
        by=["spot", "T"],
        kind="stable",
    )

full_df.to_csv(output_path, index=False)

print(f"Final merged file created: {output_path}")
PY

    [[ -s "$output_path" ]] \
        || die "Merged luminosity file not created: $output_path"
}

# ------------------------------------------------------------
# PHASE 1 - BEFORE ANNEALING
# ------------------------------------------------------------

process_before_annealing() {
    local phase="before_annealing"
    local phase_dir="$DATA_DIR/$phase"

    [[ -d "$phase_dir" ]] \
        || die "Missing required phase directory: $phase_dir"

    local run_dir
    run_dir="$(find_selected_run_dir "$phase_dir")" \
        || die "No run found for ${SENSOR}_${CONSTANT}=* in $phase_dir"

    local run_number run_prefix
    run_number="$(extract_run_number "$run_dir")"
    run_prefix="$(extract_run_prefix "$run_dir")"

    local processed_dir="$run_dir/2processed"
    local rotated_dir="$run_dir/3rotated"

    printf '\n'
    printf '============================================================\n'
    printf 'PHASE 1 - BEFORE ANNEALING\n'
    printf 'Sensor:   %s\n' "$SENSOR"
    printf 'Constant: %s\n' "$CONSTANT"
    printf 'Run:      %s\n' "$run_number"
    printf 'Folder:   %s\n' "$run_dir"
    printf '============================================================\n'

