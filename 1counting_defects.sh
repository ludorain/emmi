def mean_coordinates_per_local_spot(df: pd.DataFrame) -> pd.DataFrame:
    tmp = df.copy()
    tmp["x"] = pd.to_numeric(tmp["x"], errors="raise")
    tmp["y"] = pd.to_numeric(tmp["y"], errors="raise")

    return (
        tmp.groupby("spot", as_index=False, sort=True)
        .agg(x_mean=("x", "mean"), y_mean=("y", "mean"))
    )


def greedy_one_to_one(source_rows, target_rows, source_id, target_id,
                      sx, sy, tx, ty, radius):
    """Return one-to-one nearest-neighbour mapping within radius."""
    pairs = []
    candidate_counts = {}

    for _, src in source_rows.iterrows():
        sid = src[source_id]
        n_candidates = 0

        for _, tgt in target_rows.iterrows():
            tid = tgt[target_id]
            distance = math.hypot(
                float(src[sx]) - float(tgt[tx]),
                float(src[sy]) - float(tgt[ty]),
            )
            if distance <= radius:
                pairs.append((distance, sid, tid))
                n_candidates += 1

        candidate_counts[sid] = n_candidates

    pairs.sort(key=lambda item: item[0])

    assigned_source = set()
    assigned_target = set()
    mapping = {}
    distances = {}

    for distance, sid, tid in pairs:
        if sid in assigned_source or tid in assigned_target:
            continue
        mapping[sid] = tid
        distances[sid] = distance
        assigned_source.add(sid)
        assigned_target.add(tid)

    return mapping, distances, candidate_counts


