#!/usr/bin/env bash

# ============================================================
# AUTOMATED EMMI ANALYSIS
#
# Usage:
#   ./automatic_irradiated_analysis.sh A1 T
#   ./automatic_irradiated_analysis.sh A1 v
#   ./automatic_irradiated_analysis.sh B2 T
#
# The script must be located inside the main "emmi" directory.
#
# Implemented phases:
#   PHASE 1 - before_annealing
#   PHASE 2 - all directories matching DATA_irradiated/annealing_*
#   PHASE 3 - global hotspot-ID assignment and merge across all phases
#
# Folder structure created inside every selected run:
#   1originals
#   2processed
#   3rotated
#   4coordinates
#   5th2f
#   6luminosity
#
# ============================================================

set -Eeuo pipefail
shopt -s nullglob

# ------------------------------------------------------------
# CONFIGURATION
# ------------------------------------------------------------

BASE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DATA_DIR="$BASE_DIR/DATA_irradiated_NOisolated_changeR"

PROCESS_IMAGE="$BASE_DIR/manipulate_images/process_image.py"
TIF2TH2="$BASE_DIR/manipulate_images/tif2th2.py"

MEASURE_ROTATION="$BASE_DIR/tools_light_on/measure-rotation.py"
ROTATE_IMAGE="$BASE_DIR/tools_light_on/rotate-image.py"
