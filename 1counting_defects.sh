# to much better than one pixel.
COORD_MATCH_RADIUS="${COORD_MATCH_RADIUS:-1.0}"
MERGED_DIR="$DATA_DIR/merged_files"

# Breakdown voltages used only when T is constant and v_fin is calculated.
# A1 and B1 are the values already used in the previous analysis scripts.
#
# IMPORTANT:
# set A2/B2 here when their measured breakdown voltages are known.
VBD_A1="${VBD_A1:-51.3}"
VBD_A2="${VBD_A2:-}"
VBD_B1="${VBD_B1:-50.9}"
VBD_B2="${VBD_B2:-}"

# Global alignment table generated by PHASE 2.
ALIGNMENT_TABLE=""

# Rotated data=light image from before_annealing.
# This becomes the geometrical reference for all annealing phases.
BASE_LIGHT_REFERENCE=""

# ------------------------------------------------------------
# LOGGING / ERRORS
# ------------------------------------------------------------

log() {
    printf '\n[%s] %s\n' "$(date '+%H:%M:%S')" "$*"
}

warn() {
    printf 'WARNING: %s\n' "$*" >&2
}

die() {
    printf 'ERROR: %s\n' "$*" >&2
    exit 1
}

on_error() {
    local exit_code=$?
    local line_no=$1
    printf '\nERROR: pipeline stopped at line %s (exit code %s).\n' \
        "$line_no" "$exit_code" >&2
    exit "$exit_code"
}

trap 'on_error $LINENO' ERR

# ------------------------------------------------------------
# INPUT
# ------------------------------------------------------------

if [[ $# -ne 2 ]]; then
    cat >&2 <<EOF
Usage:
  $0 SENSOR CONSTANT

SENSOR:
  A1 | A2 | B1 | B2

CONSTANT:
  T | v

Examples:
  $0 A1 T
  $0 B1 v
EOF
    exit 1
fi

SENSOR="$1"
CONSTANT="$2"

case "$SENSOR" in
    A1|A2|B1|B2) ;;
    *) die "Invalid sensor '$SENSOR'. Allowed values: A1 A2 B1 B2." ;;
esac

case "$CONSTANT" in
    T|v) ;;
    *) die "Invalid constant '$CONSTANT'. Allowed values: T or v." ;;
esac

[[ -d "$DATA_DIR" ]] || die "DATA directory not found: $DATA_DIR"

