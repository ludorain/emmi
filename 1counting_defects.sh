        root_files = sorted(
            p for p in root_dir.glob("*data=diff*_processed_rotated_th2f.root")
            if "data=diffe" not in p.name
        )
        if not root_files:
            raise RuntimeError(f"No TH2F data=diff files found in {root_dir}")

        datasets.append({
            "phase": phase,
            "phase_order": len(datasets),
            "run_dir": run_dir,
